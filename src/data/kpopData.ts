// Verified upcoming milestone anniversaries calculated dynamically from each group's verified debutDate
export function getVerifiedGroupAnniversaries(now: Date = new Date()): FanEventRecord[] {
  const currentYear = now.getUTCFullYear();
  return KPOP_GROUPS.map((group) => {
    const [debutYearStr, monthStr, dayStr] = group.debutDate.split('-');
    const debutYear = Number(debutYearStr);
    const month = Number(monthStr);
    const day = Number(dayStr);

    let targetYear = currentYear;
    const thisYearUtc = Date.UTC(currentYear, month - 1, day, 14, 59, 0);
    if (thisYearUtc < now.getTime()) {
      targetYear += 1;
    }
    const yearsCount = targetYear - debutYear;
    const dateIso = `${targetYear}-${monthStr}-${dayStr}`;

    return {
      id: `anniv_${group.id}_${targetYear}`,
      ownerId: 'verified_catalog',
      title: `${group.name} ${yearsCount}th Debut Anniversary`,
      groupName: group.name,
      eventType: 'anniversary' as const,
      dateIso,
      kstTime: '00:00',
      sourceNote: `Verified debut date: ${group.debutDate} (${group.agency})`,
      createdAtIso: group.debutDate,
      isVerifiedBuiltIn: true,
    };
  });
}
